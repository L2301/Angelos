const element = identifier => document.getElementById(identifier);
const form = element('text-form');
let controller;

form.addEventListener('submit', async event => {
  event.preventDefault();
  if (controller) return;
  controller = new AbortController();
  element('generate-text').disabled = true;
  element('cancel-text').hidden = false;
  element('text-result').textContent = '';
  element('text-result').setAttribute('aria-busy', 'true');
  element('text-run-status').textContent = 'Loading the pinned local model and generating… First runs include model loading. No network inference.';
  element('text-run-status').classList.remove('text-error');
  element('text-provenance').textContent = 'Independent text probe. No profile, impression or training record is created.';
  try {
    const response = await fetch('/api/text-preview', {
      method: 'POST', signal: controller.signal,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: element('text-model').value,
        prompt: element('text-prompt').value,
        system: element('text-system').value,
        max_tokens: Number(element('text-max-tokens').value),
        temperature: Number(element('text-temperature').value),
        seed: Number(element('text-seed').value),
      }),
    });
    const result = await response.json();
    if (!response.ok) throw new Error(result.error ?? 'Text generation failed');
    element('text-result').textContent = result.text;
    element('text-run-status').textContent = result.finish_reason === 'length' ? 'Token limit reached: this output may be incomplete. Increase the limit or shorten the brief.' : 'Generated by a local pretrained language model. Review before using.';
    element('text-provenance').textContent = `${result.model.id} · ${result.model.revision.slice(0, 12)} · ${(result.elapsedMilliseconds / 1000).toFixed(1)}s including load · not stored`;
  } catch (error) {
    element('text-run-status').textContent = error.name === 'AbortError' ? 'Generation cancelled. No output accepted.' : error.message;
    element('text-run-status').classList.add('text-error');
  } finally {
    controller = undefined;
    element('generate-text').disabled = false;
    element('cancel-text').hidden = true;
    element('text-result').setAttribute('aria-busy', 'false');
  }
});

element('cancel-text').addEventListener('click', () => controller?.abort());
element('text-graph-preset').addEventListener('click', () => {
  element('teacher-example').value = 'qwen3-text';
  element('load-example').click();
  element('canvas-area').scrollIntoView({ behavior: 'auto', block: 'center' });
});
window.addEventListener('beforeunload', () => controller?.abort());
